#!/usr/bin/env python3
"""Wrap the mixin's raw output as the objects the platform ships.

Dashboards become GrafanaDashboard objects reconciled into the hub's Grafana
(ADR-078 add.5 §6); recording rules become PrometheusRule objects that each
cluster's VMAlert evaluates (add.5 §5).
Only the selected dashboards are shipped: control-plane, proxy, Windows and
persistent-volume dashboards read series this platform does not collect, and a
dashboard that renders empty is a defect (add.2 §2).
"""
import json, os, sys, yaml

DASHBOARDS = {
    "k8s-resources-cluster.json", "k8s-resources-multicluster.json",
    "k8s-resources-namespace.json", "k8s-resources-node.json",
    "k8s-resources-nodes-overview.json",
    "k8s-resources-pod.json", "k8s-resources-workload.json",
    "k8s-resources-workloads-namespace.json", "kubelet.json",
    "cluster-total.json", "namespace-by-pod.json", "namespace-by-workload.json",
    "pod-total.json", "workload-total.json",
}
# Recording-rule groups the selected dashboards read. Every other upstream
# group evaluates series the platform does not collect.
RULE_GROUP_PREFIXES = ("k8s.rules", "node.rules")
HEADER = "# GENERATED by scripts/observability/mixin/generate.sh. Do not edit.\n"

work, out = sys.argv[1], sys.argv[2]
root = os.path.join(out, "root")
dash_dir = os.path.join(root, "manifests/hub-core-services/platform-dashboards")
os.makedirs(dash_dir, exist_ok=True)

found = set(os.listdir(os.path.join(work, "dashboards")))
missing = sorted(DASHBOARDS - found)
if missing:
    sys.exit(f"render: the pinned mixin no longer produces {missing}; update DASHBOARDS")

# The shipped dashboards' raw JSON, for the metric allowlist (allowlist.py).
selected_dir = os.path.join(work, "selected")
os.makedirs(selected_dir, exist_ok=True)
for fname in sorted(DASHBOARDS):
    board = json.load(open(os.path.join(work, "dashboards", fname)))
    json.dump(board, open(os.path.join(selected_dir, fname), "w"))
    name = "platform-" + fname[:-len(".json")]
    obj = {
        "apiVersion": "grafana.integreatly.org/v1beta1",
        "kind": "GrafanaDashboard",
        "metadata": {
            "name": name,
            "namespace": "platform-observability",
            "annotations": {"argocd.argoproj.io/sync-options": "SkipDryRunOnMissingResource=true"},
            "labels": {"app.kubernetes.io/managed-by": "platform"},
        },
        "spec": {
            "instanceSelector": {"matchLabels": {"dashboards": "platform"}},
            "folderRef": "platform",
            "json": json.dumps(board, indent=2, sort_keys=True),
        },
    }
    with open(os.path.join(dash_dir, "dashboard-" + fname[:-len(".json")] + ".yaml"), "w") as f:
        f.write(HEADER + yaml.safe_dump(obj, sort_keys=False, width=1 << 20))

rules = json.load(open(os.path.join(work, "rules.json")))
groups = [g for g in rules.get("groups", []) if g["name"].startswith(RULE_GROUP_PREFIXES)]
if not groups:
    sys.exit("render: no recording-rule groups selected; the dashboards would read nothing")
rule = {
    "apiVersion": "monitoring.coreos.com/v1",
    "kind": "PrometheusRule",
    "metadata": {
        "name": "kubernetes-mixin-rules",
        "namespace": "platform-observability",
        "annotations": {"argocd.argoproj.io/sync-options": "SkipDryRunOnMissingResource=true"},
        "labels": {"app.kubernetes.io/managed-by": "platform", "component": "recording"},
    },
    "spec": {"groups": groups},
}
# The spoke catalogue lists its resources explicitly; the generated file has to be
# one of them or it is shipped nowhere.
KUST = "manifests/spoke/spoke-catalog/infra/kustomization.yaml"
ENTRY = "  - platform-alerts/kubernetes-mixin-rules.yaml\n"
ANCHOR = "  - platform-alerts/pipeline-health.yaml\n"
repo = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
kust = open(os.path.join(repo, KUST)).read()
if ENTRY not in kust:
    if ANCHOR not in kust:
        sys.exit(f"render: {KUST} no longer lists {ANCHOR.strip()}; place {ENTRY.strip()} by hand")
    kust = kust.replace(ANCHOR, ANCHOR + "  # Generated: the kubernetes-mixin recording rules (ADR-078 add.3 §3).\n" + ENTRY)
os.makedirs(os.path.join(root, os.path.dirname(KUST)), exist_ok=True)
open(os.path.join(root, KUST), "w").write(kust)

for rel in ("manifests/hub-core-services/platform-alerts/kubernetes-mixin-rules.yaml",
            "manifests/spoke/spoke-catalog/infra/platform-alerts/kubernetes-mixin-rules.yaml"):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(HEADER + yaml.safe_dump(rule, sort_keys=False, width=1 << 20))
