#!/usr/bin/env python3
"""Derive the metric allowlist with Grafana's mimirtool (ADR-078 add.3 §7).

    allowlist.py <mimirtool> <work dir> <generated root> <repo root>

Analyses the shipped dashboards (<work>/selected/*.json, written by render.py)
and every PrometheusRule the platform ships -- the generated ones from this run
and the hand-written ones already in the repository -- with `mimirtool analyze
dashboard` and `analyze rule-file`, which parse PromQL properly. Writes
scripts/observability/mixin/metrics-allowlist.json into the generated root.
A query mimirtool cannot parse fails generation: its metrics would otherwise be
dropped without a word.
"""
import glob, json, os, subprocess, sys
import yaml

tool, work, gen, repo = sys.argv[1:5]
RULE_DIRS = ("manifests/hub-core-services/platform-alerts",
             "manifests/spoke/spoke-catalog/infra/platform-alerts")

files = {}
for base in (repo, gen):            # this run's output overrides the committed copy
    for d in RULE_DIRS:
        for f in glob.glob(os.path.join(base, d, "*.yaml")):
            files[os.path.relpath(f, base)] = f
rules_dir = os.path.join(work, "rule-files")
os.makedirs(rules_dir, exist_ok=True)
n = 0
for rel, f in sorted(files.items()):
    for doc in yaml.safe_load_all(open(f)):
        if doc and doc.get("kind") == "PrometheusRule":
            n += 1
            yaml.safe_dump({"groups": doc["spec"]["groups"]},
                           open(os.path.join(rules_dir, f"{n:03d}.yaml"), "w"))
if n == 0:
    sys.exit("allowlist: no PrometheusRule found; the platform ships rules")

dashboards = sorted(glob.glob(os.path.join(work, "selected", "*.json")))
if not dashboards:
    sys.exit("allowlist: no selected dashboards; render.py writes them first")
g_out, r_out = os.path.join(work, "in-grafana.json"), os.path.join(work, "in-ruler.json")
subprocess.run([tool, "analyze", "dashboard", f"--output={g_out}", *dashboards], check=True,
               stdout=subprocess.DEVNULL)
subprocess.run([tool, "analyze", "rule-file", f"--output={r_out}",
                *sorted(glob.glob(os.path.join(rules_dir, "*.yaml")))], check=True,
               stdout=subprocess.DEVNULL)

g, r = json.load(open(g_out)), json.load(open(r_out))
errors = [f"dashboard {d.get('title')}: {e}" for d in g.get("dashboards", []) for e in (d.get("parse_errors") or [])]
errors += [f"rule: {e}" for e in (r.get("parse_errors") or [])]
if errors:
    sys.exit("allowlist: mimirtool could not parse: " + "; ".join(errors))

used = set(g.get("metricsUsed") or []) | set(r.get("metricsUsed") or [])
used = {m for m in used if ":" not in m}   # recording-rule outputs are produced in the ruler
used.add("up")                              # a scrape's own health: pipeline-health and §15 read it
dest = os.path.join(gen, "scripts/observability/mixin/metrics-allowlist.json")
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest, "w") as f:
    json.dump({"source": "mimirtool 3.2.3 analyze dashboard + rule-file, over the shipped dashboards "
                         "and PrometheusRules; regenerated by scripts/observability/mixin/generate.sh",
               "metrics": sorted(used)}, f, indent=2)
    f.write("\n")
